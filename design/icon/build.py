"""Build every Heraldo icon output from design/icon/heraldo.svg, the source of truth.

    uv run design/icon/build.py            # masters, layers, export/, geometry.json
    uv run design/icon/build.py --apple    # also rewrite apple/App/AppIcon.icon

It reads the paths h, rule, rule-small, rule-circle and rule-circle-small, the
wordmark and wordmark-small groups, and the ink, cream and red classes, from
heraldo.svg. It only transforms that geometry:
it translates for optical centring, scales to fit the circle layout, swaps
colours and sets opacity. It never draws new geometry. Needs rsvg-convert and
ImageMagick 7 (magick). Every path is relative to this file.
"""
import argparse
import io
import json
import math
import re
import shutil
import subprocess
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np
import pathops
from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.svgLib.path import parse_path
from PIL import Image

HERE = Path(__file__).resolve().parent
MASTER = HERE / "heraldo.svg"
APPLE_APP = HERE.parent.parent / "apple" / "App"
APPICON = APPLE_APP / "AppIcon.icon"
XCASSETS = APPLE_APP / "Shared" / "Assets.xcassets"
LOGO = HERE / "export" / "logo"
HEADER_PX = 40          # web header logo height (1x)
WORDMARK_HEADER_PX = 28  # web header wordmark height (1x), from wordmark-small
BANNER = (1280, 320)    # README banner
WORDMARK_PT = 64        # asset catalog wordmark height
MENU_BAR_PT = 18        # macOS menu bar icon height
NS = {"svg": "http://www.w3.org/2000/svg"}

CIRCLE_R = 392   # circle layout: no pixel beyond this radius (the safe zone is 409.6)
LAYOUTS = {      # name: (rule id, fit to circle)
    "squircle": ("rule", False),
    "squircle-small": ("rule-small", False),
    "circle": ("rule-circle", True),
    "circle-small": ("rule-circle-small", True),
}
GENERATED = "<!-- Generated by design/icon/build.py from heraldo.svg. Do not edit. -->\n"


def read_master():
    tree = ET.parse(MASTER)
    style = "".join(e.text or "" for e in tree.iter("{%s}style" % NS["svg"]))
    palette = {k: v.upper() for k, v in re.findall(r"\.(\w+)\s*\{\s*fill:\s*(#[0-9A-Fa-f]{6})", style)}
    paths = {}
    for e in tree.iter("{%s}path" % NS["svg"]):
        p = pathops.Path()
        parse_path(e.get("d"), p.getPen())
        paths[e.get("id")] = p
    return palette, paths


def ntos(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def path_d(p):
    """SVG path data, without the explicit closing segment pathops draws back to
    each contour's start (Z already closes it)."""
    rec = RecordingPen()
    p.draw(rec)
    ops, start = list(rec.value), None
    keep = []
    for i, (op, args) in enumerate(ops):
        if op == "moveTo":
            start = args[0]
        nxt = ops[i + 1][0] if i + 1 < len(ops) else None
        if op == "lineTo" and nxt == "closePath" and ntos(args[0][0]) == ntos(start[0]) \
                and ntos(args[0][1]) == ntos(start[1]):
            continue
        keep.append((op, args))
    pen = SVGPathPen(None, ntos=ntos)
    for op, args in keep:
        getattr(pen, op)(*args)
    return pen.getCommands()


def moved(p, m):
    out = pathops.Path()
    p.draw(TransformPen(out.getPen(), m))
    return out


def svg(parts, ground=None):
    bg = f'<rect width="1024" height="1024" fill="{ground}"/>\n  ' if ground else ""
    body = "\n  ".join(f'<path fill="{c}" d="{d}"/>' for c, d in parts)
    return (GENERATED + '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" '
            f'viewBox="0 0 1024 1024">\n  {bg}{body}\n</svg>\n')


def coverage(*paths):
    png = subprocess.run(["rsvg-convert", "-w", "1024", "-h", "1024"],
                         input=svg([("#000", path_d(p)) for p in paths]).encode(),
                         capture_output=True, check=True).stdout
    return np.asarray(Image.open(io.BytesIO(png)).convert("RGBA"))[:, :, 3] > 127


def place(h, r, fit_circle):
    """Optical centring of H + rule as one mass: x to the area-weighted centroid,
    y to the midpoint of centroid and bbox centre. For the circle layout, scale
    about the centre so the farthest pixel sits at CIRCLE_R."""
    for _ in range(2):
        ys, xs = np.nonzero(coverage(h, r))
        m = (1, 0, 0, 1, 512 - xs.mean(), 512 - (ys.mean() + (ys.min() + ys.max()) / 2) / 2)
        h, r = moved(h, m), moved(r, m)
        if fit_circle:
            ys, xs = np.nonzero(coverage(h, r))
            k = CIRCLE_R / np.hypot(xs + 0.5 - 512, ys + 0.5 - 512).max()
            m = (k, 0, 0, k, 512 * (1 - k), 512 * (1 - k))
            h, r = moved(h, m), moved(r, m)
    ys, xs = np.nonzero(coverage(h, r))
    stats = {"bbox": [int(xs.min()), int(ys.min()), int(xs.max()), int(ys.max())],
             "centroid": [round(float(xs.mean()), 1), round(float(ys.mean()), 1)],
             "max_radius": round(float(np.hypot(xs + 0.5 - 512, ys + 0.5 - 512).max()), 1),
             "rule_area": round(abs(r.area))}
    return h, r, stats


def build_svgs(palette, paths):
    ink, cream, red = palette["ink"], palette["cream"], palette["red"]
    themes = {"dark": (ink, cream), "light": (cream, ink)}   # (ground, H)
    masters, layers = HERE / "masters", HERE / "layers"
    for d in (masters, layers):
        d.mkdir(exist_ok=True)
    geometry = {}
    for layout, (rid, fit) in LAYOUTS.items():
        h, r, geometry[layout] = place(paths["h"], paths[rid], fit)
        hd, rd = path_d(h), path_d(r)
        name, small = layout.removesuffix("-small"), layout.endswith("-small")
        for theme, (ground, mark) in themes.items():
            out = masters / f"heraldo-{name}-{theme}{'-small' if small else ''}.svg"
            out.write_text(svg([(mark, hd), (red, rd)], ground))
        if not small:
            (layers / f"{name}-h-ink.svg").write_text(svg([(ink, hd)]))
            (layers / f"{name}-h-cream.svg").write_text(svg([(cream, hd)]))
            (layers / f"{name}-rule.svg").write_text(svg([(red, rd)]))
            (layers / f"{name}-rule-cream.svg").write_text(svg([(cream, rd)]))
    (HERE / "geometry.json").write_text(json.dumps(geometry, indent=1) + "\n")
    return geometry


# ---- Mark-only logos: the H and rule cropped to their bounds (viewBox only).
def mark_svg(parts, bounds, height=None):
    x0, y0, x1, y1 = bounds
    w, h = x1 - x0, y1 - y0
    size = f' width="{ntos(w * height / h)}" height="{height}"' if height else ""
    body = "\n  ".join(f'<path fill="{c}" d="{d}"/>' for c, d in parts)
    return (GENERATED + f'<svg xmlns="http://www.w3.org/2000/svg"{size} '
            f'viewBox="{ntos(x0)} {ntos(y0)} {ntos(w)} {ntos(h)}">\n  {body}\n</svg>\n')


def mark_bounds(*paths, pad=0):
    b = [p.bounds for p in paths]
    x0, y0 = min(v[0] for v in b), min(v[1] for v in b)
    x1, y1 = max(v[2] for v in b), max(v[3] for v in b)
    return (math.floor(x0 - pad), math.floor(y0 - pad), math.ceil(x1 + pad), math.ceil(y1 + pad))


def imageset(name, files, props):
    d = XCASSETS / f"{name}.imageset"
    if d.exists():
        shutil.rmtree(d)
    d.mkdir(parents=True)
    images = []
    for fname, text, dark in files:
        (d / fname).write_text(text)
        img = {"filename": fname, "idiom": "universal"}
        if dark:
            img["appearances"] = [{"appearance": "luminosity", "value": "dark"}]
        images.append(img)
    (d / "Contents.json").write_text(json.dumps(
        {"images": images, "info": {"author": "xcode", "version": 1}, "properties": props}, indent=2) + "\n")


def build_logos(palette, paths):
    """Web logos and the Apple asset catalog. Full colour uses the squircle
    geometry; the menu bar icon uses the small-size geometry."""
    ink, cream, red = palette["ink"], palette["cream"], palette["red"]
    h, r, _ = place(paths["h"], paths["rule"], False)
    hs, rs, _ = place(paths["h"], paths["rule-small"], False)
    hd, rd, hsd, rsd = path_d(h), path_d(r), path_d(hs), path_d(rs)
    b, bs = mark_bounds(h, r), mark_bounds(hs, rs)
    LOGO.mkdir(parents=True, exist_ok=True)
    variants = {"light": [(ink, hd), (red, rd)],          # for light grounds
                "dark": [(cream, hd), (red, rd)],         # for dark grounds
                "mono": [("currentColor", hd), ("currentColor", rd)]}
    for name, parts in variants.items():
        (LOGO / f"heraldo-mark-{name}.svg").write_text(mark_svg(parts, b))
    for name in ("light", "dark"):
        src = LOGO / f"heraldo-mark-{name}.svg"
        for scale, suffix in ((1, ""), (2, "@2x")):
            dst = LOGO / f"heraldo-mark-{name}-{HEADER_PX}{suffix}.png"
            rasterize(src, dst, h=HEADER_PX * scale)
    # Open Graph image, mark only: the dark mark centred on ink, 60% of the height.
    # The default og-image.* carries the wordmark (build_wordmark).
    og_svg = LOGO / "og-image-mark.svg"
    og_svg.write_text(ground_svg((1200, 630), ink, [(cream, hd), (red, rd)], b, 630 * 0.6))
    rasterize(og_svg, LOGO / "og-image-mark.png", 1200, 630)

    # Apple asset catalog.
    XCASSETS.mkdir(parents=True, exist_ok=True)
    (XCASSETS / "Contents.json").write_text(json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n")
    vector = {"preserves-vector-representation": True}
    template = {"preserves-vector-representation": True, "template-rendering-intent": "template"}
    imageset("HeraldoMark", [("HeraldoMark.svg", mark_svg(variants["light"], b, 128), False),
                             ("HeraldoMark-dark.svg", mark_svg(variants["dark"], b, 128), True)], vector)
    # Template images: both parts opaque black, so the rule keeps its shape when tinted.
    imageset("HeraldoMarkTemplate", [("HeraldoMarkTemplate.svg",
                                      mark_svg([("#000000", hd), ("#000000", rd)], b, 128), False)], template)
    imageset("MenuBarIcon", [("MenuBarIcon.svg",
                              mark_svg([("#000000", hsd), ("#000000", rsd)], bs, MENU_BAR_PT), False)], template)


def ground_svg(size, ground, parts, bounds, height):
    """`parts` scaled to `height` and centred on a `size` canvas filled with `ground`."""
    W, H = size
    x0, y0, x1, y1 = bounds
    k = height / (y1 - y0)
    tx, ty = W / 2 - (x0 + x1) / 2 * k, H / 2 - (y0 + y1) / 2 * k
    body = "\n".join(f'    <path fill="{c}" d="{d}"/>' for c, d in parts)
    return (GENERATED + f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">\n'
            f'  <rect width="{W}" height="{H}" fill="{ground}"/>\n'
            f'  <g transform="matrix({ntos(k)} 0 0 {ntos(k)} {ntos(tx)} {ntos(ty)})">\n{body}\n  </g>\n</svg>\n')


def rasterize(src, dst, w=None, h=None):
    size = (["-w", str(w)] if w else []) + (["-h", str(h)] if h else [])
    subprocess.run(["rsvg-convert", *size, str(src), "-o", str(dst)], check=True)


# ---- Wordmark: "Heraldo" in Chomsky over the rule (tools/wordmark_from_font.py).
def wordmark(paths, prefix):
    """(letters d, rule d, bounds) for the `wordmark` or `wordmark-small` group."""
    ids = [k for k in paths if re.fullmatch(rf"{prefix}-[a-z]", k)]
    letters, rule = [paths[k] for k in ids], paths[f"{prefix}-rule"]
    return " ".join(path_d(p) for p in letters), path_d(rule), mark_bounds(*letters, rule)


def build_wordmark(palette, paths):
    """Wordmark logos, header PNGs, README banners, the default og-image and the
    HeraldoWordmark asset. Display geometry everywhere except the header PNGs,
    which use wordmark-small (looser tracking, heavier rule)."""
    ink, cream, red = palette["ink"], palette["cream"], palette["red"]
    for prefix in ("wordmark", "wordmark-small"):
        ld, rd, b = wordmark(paths, prefix)
        variants = {"light": [(ink, ld), (red, rd)], "dark": [(cream, ld), (red, rd)],
                    "mono": [("currentColor", ld), ("currentColor", rd)]}
        for name, parts in variants.items():
            (LOGO / f"heraldo-{prefix}-{name}.svg").write_text(mark_svg(parts, b))
    for name in ("light", "dark"):
        src = LOGO / f"heraldo-wordmark-small-{name}.svg"
        for scale, suffix in ((1, ""), (2, "@2x")):
            rasterize(src, LOGO / f"heraldo-wordmark-{name}-{WORDMARK_HEADER_PX}{suffix}.png",
                      h=WORDMARK_HEADER_PX * scale)
    ld, rd, b = wordmark(paths, "wordmark")
    themes = {"light": (cream, ink), "dark": (ink, cream)}   # (ground, letters)
    for name, (ground, fg) in themes.items():
        out = LOGO / f"readme-banner-{name}.svg"
        out.write_text(ground_svg(BANNER, ground, [(fg, ld), (red, rd)], b, BANNER[1] * 0.46))
        rasterize(out, out.with_suffix(".png"), *BANNER)
    og = LOGO / "og-image.svg"
    og.write_text(ground_svg((1200, 630), ink, [(cream, ld), (red, rd)], b, 630 * 0.38))
    rasterize(og, LOGO / "og-image.png", 1200, 630)
    imageset("HeraldoWordmark", [("HeraldoWordmark.svg", mark_svg([(ink, ld), (red, rd)], b, WORDMARK_PT), False),
                                 ("HeraldoWordmark-dark.svg", mark_svg([(cream, ld), (red, rd)], b, WORDMARK_PT), True)],
             {"preserves-vector-representation": True})


def render(src, dst, px):
    subprocess.run(["rsvg-convert", "-w", str(px), "-h", str(px), str(src), "-o", str(dst)], check=True)


def magick(*args):
    # -strip and no date chunks keep the PNGs byte-identical across builds.
    *ins, out = map(str, args)
    subprocess.run(["magick", *ins, "-strip", "-define", "png:exclude-chunks=date,time", out], check=True)


def build_web(palette):
    """Web set from the dark theme: favicons from the small master, the rest from
    the squircle master, the maskable icon from the circle master."""
    out = HERE / "export"
    out.mkdir(exist_ok=True)
    m = HERE / "masters"
    tmp = out / ".tmp-1024.png"
    render(m / "heraldo-squircle-dark-small.svg", tmp, 1024)
    magick(tmp, "-resize", "32x32", "-unsharp", "0x0.5", out / "favicon-32x32.png")
    magick(tmp, "-resize", "16x16", "-unsharp", "0x0.5", out / "favicon-16x16.png")
    magick(out / "favicon-16x16.png", out / "favicon-32x32.png", out / "favicon.ico")
    render(m / "heraldo-squircle-dark.svg", tmp, 1024)
    magick(tmp, "-resize", "180x180", "-background", palette["ink"], "-alpha", "remove", "-alpha", "off",
           out / "apple-touch-icon.png")
    magick(tmp, "-resize", "192x192", out / "icon-192.png")
    magick(tmp, "-resize", "512x512", out / "icon-512.png")
    render(m / "heraldo-circle-dark.svg", tmp, 1024)
    magick(tmp, "-resize", "512x512", out / "icon-maskable-512.png")
    tmp.unlink()


def srgb(hexcol):
    r, g, b = (int(hexcol[i:i + 2], 16) / 255 for i in (1, 3, 5))
    return f"srgb:{r:.5f},{g:.5f},{b:.5f},1"


def icon_json(palette):
    return {
        "fill-specializations": [
            {"value": {"solid": srgb(palette["cream"])}},
            {"appearance": "dark", "value": {"solid": srgb(palette["ink"])}},
        ],
        "groups": [
            {   # Front: the rule catches its own highlight above the H.
                "name": "Rule",
                "layers": [{
                    "name": "rule", "glass": True,
                    # Tinted and clear are monochrome and map luminance: red would go
                    # dark and vanish on a dark tint. A cream rule at reduced opacity
                    # stays a distinct, dimmer bar under the full-strength H.
                    "image-name-specializations": [
                        {"value": "rule.svg"},
                        {"appearance": "tinted", "value": "rule-cream.svg"},
                    ],
                    "opacity-specializations": [{"value": 1}, {"appearance": "tinted", "value": 0.6}],
                }],
                "shadow": {"kind": "layer-color", "opacity": 0.35},
                "translucency": {"enabled": True, "value": 0.2},
                "lighting": "individual",
                "specular": True,
            },
            {   # Back: the H is the main glass layer.
                "name": "H",
                "layers": [{
                    "name": "h",
                    "image-name-specializations": [
                        {"value": "h-ink.svg"},
                        {"appearance": "dark", "value": "h-cream.svg"},
                        {"appearance": "tinted", "value": "h-cream.svg"},
                    ],
                    "glass": True,
                }],
                "shadow": {"kind": "neutral", "opacity": 0.5},
                "translucency": {"enabled": True, "value": 0.35},
                "lighting": "combined",
                "specular": True,
            },
        ],
        "supported-platforms": {"squares": "shared", "circles": ["watchOS"]},
    }


def build_apple(palette):
    assets = APPICON / "Assets"
    if assets.exists():
        shutil.rmtree(assets)
    assets.mkdir(parents=True)
    for name in ("h-ink", "h-cream", "rule", "rule-cream"):
        shutil.copy(HERE / "layers" / f"squircle-{name}.svg", assets / f"{name}.svg")
    (APPICON / "icon.json").write_text(json.dumps(icon_json(palette), indent=2) + "\n")


def main():
    ap = argparse.ArgumentParser(description="Build the Heraldo icon from heraldo.svg.")
    ap.add_argument("--apple", action="store_true", help="also rewrite apple/App/AppIcon.icon")
    a = ap.parse_args()
    palette, paths = read_master()
    geometry = build_svgs(palette, paths)
    build_web(palette)
    build_logos(palette, paths)
    build_wordmark(palette, paths)
    if a.apple:
        build_apple(palette)
    print(json.dumps(geometry, indent=1))


if __name__ == "__main__":
    main()
